"""Catalogue of every lighting configuration in tools/synth.py with its results.

  python configs_catalog.py     -> docs/lighting_configs.md + docs/lighting_configs.json
Results are read from the synth reports copied to docs/ (synth_report_*.txt); a variant without a
result has not been trained yet. Re-run after adding a set / variant or copying a new report.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np

import ledsim
import sweep
import synth

DOCS = Path(__file__).resolve().parent.parent / "docs"
# set -> reports holding its results (later ones override earlier ones)
REPORTS = {"main": ["synth_report_1seed.txt", "synth_report_seeds.txt"],
           "vertical": ["synth_report_vertical.txt"], "triangle": ["synth_report_triangle.txt"]}


def in_view(p):
    f = sweep.lens_f(*sweep.LENSES["120"])
    u, v = sweep.project(np.asarray(p, float)[None], ledsim.CAM, ledsim.AIM - ledsim.CAM, "fisheye", f)[0]
    return bool(0 <= u < sweep.W and 0 <= v < sweep.H)


def rel(p, origin):
    return [round(float(x), 1) for x in (np.asarray(p) - origin)]


def read_report(name):
    path = DOCS / name
    if not path.exists():
        return {}
    txt = path.read_text().splitlines()
    hdr = next(i for i, l in enumerate(txt) if l.startswith("variant"))
    cols = txt[hdr].split()[1:]
    seeds = re.search(r"seeds \[([\d, ]+)\]", txt[0])
    out = {}
    for l in txt[hdr + 1:]:
        m = re.match(r"^(.*?)\s+(0\.\d{3})\s", l)
        if m:
            vals = [float(x) for x in l[len(m.group(1)):].split()]
            if len(vals) == len(cols) - 1:      # older reports have no +- column
                vals.insert(1, float("nan"))
            d = dict(zip(cols, vals))
            d["report"] = name
            d["seeds"] = len(seeds.group(1).split(",")) if seeds else 1
            out[m.group(1).strip()] = d
    return out


def main():
    cat = {"frame": "x = wearer's left (+), y = up, z = forward (out of the face), mm. rel_slit = from the mouth "
                    "slit (x, mm above, mm in front); rel_cam = from the camera lens",
           "camera": {"rel_slit": rel(ledsim.CAM, synth.SLIT), "aim_rel_slit": rel(ledsim.AIM, synth.SLIT),
                      "lens": "OV2640 120 deg"},
           "metric": "val MAE of the mouth CNN on 1200 held-out synthetic frames, lower is better", "sets": {}}
    for sname, (leds, variants, fname) in synth.SETS.items():
        res = {}
        for rep in REPORTS.get(sname, []):
            res.update(read_report(rep))
        cat["sets"][sname] = {
            "data": f"out/synth/{fname}",
            "render": f"python synth.py render --n 6000 --set {sname}",
            "train": f"python synth.py train --set {sname} --epochs 60 --seeds 0,1,2",
            "leds": {k: {"rel_slit": rel(v, synth.SLIT), "rel_cam": rel(v, ledsim.CAM), "in_camera_view": in_view(v)}
                     for k, v in leds.items()},
            "variants": {vn: {"channels": ch, "phases": len(ch), "result": res.get(vn)} for vn, ch in variants.items()},
        }
    (DOCS / "lighting_configs.json").write_text(json.dumps(cat, indent=1))

    L = ["# Lighting configurations (mouth camera)", "",
         "Generated by `tools/configs_catalog.py` from `tools/synth.py` and the reports in this folder; "
         "machine-readable copy `lighting_configs.json`.",
         f"Coordinates: (x, mm above the mouth slit, mm in front of it), x > 0 = wearer's left; camera at "
         f"{tuple(cat['camera']['rel_slit'])}, 120 deg lens.",
         "Result: val MAE of the mouth CNN on held-out synthetic frames (lower is better), pucker in brackets, "
         "number of training seeds averaged. Numbers compare only within one set (same rendered frames).", ""]
    for sname, s in cat["sets"].items():
        L += [f"## Set `{sname}`", "", f"Data `{s['data']}` (not in git). Re-run: `cd tools && {s['render']} && {s['train']}`", "",
              "| LED | from slit | from camera | in camera view |", "|---|---|---|---|"]
        L += [f"| {k} | {tuple(v['rel_slit'])} | {tuple(v['rel_cam'])} | {'YES' if v['in_camera_view'] else 'no'} |"
              for k, v in s["leds"].items()]
        L += ["", "| Variant | frames | channels (each = LEDs lit together) | MAE all (pucker) | seeds |", "|---|---|---|---|---|"]
        for vn, v in s["variants"].items():
            r = v["result"]
            rs, sd = ("not run", "") if r is None else (f"{r['all']:.3f} ({r['pucker']:.3f})", str(r["seeds"]))
            L.append(f"| {vn} | {v['phases']} | {' / '.join('+'.join(c) for c in v['channels'])} | {rs} | {sd} |")
        L.append("")
    L += ["## Pixel-metric sweeps (layouts lit together, no trained net)", "",
          "- `tools/ledsim.py` (round 1): 137 spots, x 0/15/30/45, y 70-150, z 270-330 mm absolute -> `led_report.txt`, "
          "`led_layouts.png`; blinking check `tools/ledsim2ch.py` -> `led_report_2ch.txt`.",
          "- `tools/ledsweep2.py` (round 2): 769 spots, x 0/10/20/30/45, y slit-40..+60, z 265-340, wall bounce -> "
          "`led2_report.txt`, `led2_layouts.png`, `led2_map.png`; wider pairs `--xs 45,55,65,75 --hpairs-only "
          "--out led2_wide` -> `led2_wide_report.txt`.",
          "- These cannot judge blinking: use `synth.py` with a trained net for that.", "",
          "## Adding an idea", "",
          "1. Add LED spots + variants as a new entry of `SETS` in `tools/synth.py` (or a variant to an existing set: "
          "its frames are already rendered, only training is needed).",
          "2. Keep LEDs in free space and outside the camera view (this catalogue flags `in camera view`).",
          "3. Render (~10 min for 6000 frames x 10 LEDs), train (~16 s per run), copy the report to docs/ and add it to "
          "`REPORTS` here, run this script.",
          "4. Keep a reference variant (e.g. `ref blink U1/D1`, `ref both U1+D1`) in every new set."]
    (DOCS / "lighting_configs.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", DOCS / "lighting_configs.md")


if __name__ == "__main__":
    main()
