"""Export out/model/mouth.pt to C++ weights for firmware/lib/mouth_net (BatchNorm folded).

  python export_c.py      -> firmware/lib/mouth_net/mouth_weights.h
Conv weights are stored [out][ky][kx][in] (HWC activations on the chip), the head [out][in].
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import torch

import train

ROOT = Path(__file__).resolve().parent.parent
DST = ROOT / "firmware" / "lib" / "mouth_net" / "mouth_weights.h"


def folded(model):
    """[(w (out, 3, 3, in), b (out,), pool)] for every conv block."""
    mods = list(model.features)
    layers = []
    for i, m in enumerate(mods):
        if not isinstance(m, torch.nn.Conv2d):
            continue
        bn = mods[i + 1]
        pool = i + 3 < len(mods) and isinstance(mods[i + 3], torch.nn.MaxPool2d)
        s = (bn.weight / torch.sqrt(bn.running_var + bn.eps)).detach()
        w = (m.weight.detach() * s[:, None, None, None]).permute(0, 2, 3, 1).numpy()
        b = (bn.bias.detach() - bn.running_mean * s).numpy()
        layers.append((w.astype(np.float32), b.astype(np.float32), pool))
    return layers


def arr(name, a):
    flat = ", ".join(f"{v:.8g}f" for v in a.ravel())
    return f"static const float {name}[{a.size}] = {{{flat}}};\n"


def main():
    meta = json.loads((train.OUT / "mouth.json").read_text())
    model = train.MouthNet(width=tuple(meta.get("width", (16, 24, 32, 48, 64))))
    model.load_state_dict(torch.load(train.OUT / "mouth.pt", map_location="cpu"))
    model.eval()
    layers = folded(model)
    meta = json.loads((train.OUT / "mouth.json").read_text())
    out = ["// Generated by tools/export_c.py from out/model/mouth.pt - do not edit.\n#pragma once\n\n",
           f"#define MOUTH_IN_W {train.IN_W}\n#define MOUTH_IN_H {train.IN_H}\n",
           f"#define MOUTH_N_LAYERS {len(layers)}\n#define MOUTH_N_OUT {len(meta['channels'])}\n\n",
           "static const char* const kMouthChannels[MOUTH_N_OUT] = {"
           + ", ".join(f'"{c}"' for c in meta["channels"]) + "};\n\n"]
    for k, (w, b, pool) in enumerate(layers):
        out.append(arr(f"kW{k}", w))
        out.append(arr(f"kB{k}", b))
    hw = model.head.weight.detach().numpy().astype(np.float32)
    hb = model.head.bias.detach().numpy().astype(np.float32)
    out.append(arr("kHeadW", hw))
    out.append(arr("kHeadB", hb))
    out.append("\nstruct MouthLayerDef { int cin, cout; bool pool; const float* w; const float* b; };\n")
    out.append("static const MouthLayerDef kMouthLayers[MOUTH_N_LAYERS] = {\n")
    for k, (w, b, pool) in enumerate(layers):
        out.append(f"    {{{w.shape[3]}, {w.shape[0]}, {'true' if pool else 'false'}, kW{k}, kB{k}}},\n")
    out.append("};\n")
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("".join(out))
    n = sum(w.size + b.size for w, b, _ in layers) + hw.size + hb.size
    print(f"wrote {DST} ({n} floats, {n * 4 / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
